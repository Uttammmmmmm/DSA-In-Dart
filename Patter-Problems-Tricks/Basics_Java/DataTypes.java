
//  Data Types in Java

// Primitives vs Non-Primitives
// 1. Primitive Data Types --> byte, short, int, long, float, double, char, boolean

// byte: 1 byte and between -128 to 127
// short: 2 bytes and between -32,768 to 32,767
// int: 4 bytes and between -2,147,483,648 to 2,147,483,647
// long: 8 bytes and between -9,223,372,036,854,775,808 to 9,223,372,036,854,775,807
// float: 4 bytes and between 1.4E-45 to 3.4028235E38
// double: 8 bytes and between 4.9E-324 to 1.7976931348623157E308
// char: 2 bytes and between '\u0000' to '\uffff'
// boolean: 1 bit and values true and false

// 2. Non-Primitive Data Types --> String, Arrays, Classes, Interfaces

// String: A sequence of characters, used to store text.
// Arrays: A collection of similar data types.
// Classes: Blueprints for creating objects, encapsulating data and behavior.
// Interfaces: Abstract types used to specify a set of methods that a class must implement.

public class DataTypes {
    public static void main(String args[]) {
        String name = "Uttam Singh";
        System.out.println(name);
    }
}
